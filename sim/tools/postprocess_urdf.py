#!/usr/bin/env python3
"""Turn the raw Hiwonder xacro output into a sim-ready URDF.

- rewrites package:// mesh paths to paths relative to sim/urdf/
- applies the calibrated joint limits (URDF angle convention)
- adds a calibrated `tcp` frame matching Hiwonder's FK end-effector frame

  python3 sim/tools/postprocess_urdf.py raw.urdf sim/urdf/jetarm_6dof.urdf
"""
from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

# URDF joint limits derived from the real FK mechanical limits through the
# pulse->DH->URDF mapping. All symmetric in the URDF convention.
LIMITS = {
    "joint1": (-2.0979, 2.0979),   # +-120.2 deg
    "joint2": (-1.5743, 1.5743),   # +-90.2 deg  (real mechanical range, not servo range)
    "joint3": (-2.0979, 2.0979),   # +-120.2 deg
    "joint4": (-1.9234, 1.9234),   # +-110.2 deg (real mechanical range)
    "joint5": (-2.0979, 2.0979),   # +-120.2 deg
}

TCP_XYZ = "0 0 -0.00354416798"
TCP_RPY = "0 -1.57079632679 0"

HEADER = """<?xml version="1.0"?>
<!-- Generated by sim/tools/postprocess_urdf.py from the Hiwonder xacro.
     Source: sim/assets/jetarm_6dof_description (© Hiwonder).
     Kinematics verified against the real FK (sim/calibration/fk_report.json).
     Inertials are still placeholders; see sim/calibration/joint_map.yaml. -->
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("dst")
    args = ap.parse_args()

    text = Path(args.src).read_text()
    text = text.replace("package://jetarm_6dof_description/", "../assets/jetarm_6dof_description/")
    root = ET.fromstring(text)

    for joint in root.findall("joint"):
        name = joint.get("name")
        if name in LIMITS:
            lim = joint.find("limit")
            if lim is None:
                lim = ET.SubElement(joint, "limit")
            lo, hi = LIMITS[name]
            lim.set("lower", f"{lo:.6f}")
            lim.set("upper", f"{hi:.6f}")

    if root.find("./link[@name='tcp']") is None:
        ET.SubElement(root, "link", {"name": "tcp"})
        j = ET.SubElement(root, "joint", {"name": "tcp_joint", "type": "fixed"})
        ET.SubElement(j, "origin", {"xyz": TCP_XYZ, "rpy": TCP_RPY})
        ET.SubElement(j, "parent", {"link": "endpoint"})
        ET.SubElement(j, "child", {"link": "tcp"})

    ET.indent(root, space="  ")
    body = ET.tostring(root, encoding="unicode")
    Path(args.dst).parent.mkdir(parents=True, exist_ok=True)
    Path(args.dst).write_text(HEADER + body + "\n")
    print(f"wrote {args.dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
